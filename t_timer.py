from harness import *
srv=serve()
try:
  with sync_playwright() as p:
    b,pg,errs=newpage(p,touch=True,h=800)
    pg.route("**/dabsy-brain.swagatdemo9292.workers.dev**",lambda r:r.fulfill(status=500,body="{}"))
    pg.evaluate("window.DABSy.require('session')"); pg.wait_for_timeout(1500)
    pg.evaluate("()=>{const D=window.DABSy;const t=D.tasks.add({title:'Physics: kinematics',subject:'physics',category:'study',durationMin:25,priority:'normal'});D.session.startQuick(t)}")
    pg.wait_for_selector("#session-dock.in",timeout=6000); pg.wait_for_timeout(900)
    box=lambda:pg.evaluate("(()=>{const r=document.getElementById('session-dock').getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height}})()")
    bx=box(); print(bx)
    check("compact floating pill (small, rounded, bottom of screen)",bx['w']<=260 and bx['h']<=72 and bx['y']>650,bx)
    check("clear time display",pg.evaluate("/\\d\\d:\\d\\d/.test(document.getElementById('sd-time').textContent)"),pg.inner_text("#sd-time"))
    check("progress ring present",pg.locator("#sd-arc").count()==1)
    check("pause is immediately accessible without expanding",pg.locator("#sd-pause-c").is_visible())
    t1=pg.inner_text("#sd-time"); pg.wait_for_timeout(2200); t2=pg.inner_text("#sd-time")
    check("running: time counts down",t1!=t2,(t1,t2))
    pg.screenshot(path="/tmp/shots/timer_compact.png")
    pg.click("#sd-pause-c"); pg.wait_for_timeout(400)
    p1=pg.inner_text("#sd-time"); pg.wait_for_timeout(2300); p2=pg.inner_text("#sd-time")
    check("pause stops the clock",p1==p2 and pg.evaluate("document.getElementById('session-dock').dataset.run")=="paused",(p1,p2))
    check("button becomes Resume",pg.get_attribute("#sd-pause-c","aria-label")=="Resume")
    pg.click("#sd-pause-c"); pg.wait_for_timeout(2300); p3=pg.inner_text("#sd-time")
    check("resume continues from where it stopped (no jump)",p3!=p2 and p3<=p2 and (int(p2[:2])*60+int(p2[3:]))-(int(p3[:2])*60+int(p3[3:]))<=4,(p2,p3))
    # expansion
    pg.click(".sd-top .sd-clock"); pg.wait_for_timeout(800)
    check("tap expands to show controls",pg.evaluate("document.getElementById('session-dock').dataset.open")=="1" and pg.locator("#sd-end").is_visible() and pg.locator("#sd-skip").is_visible())
    bx2=box(); check("expanded stays on screen",bx2['y']>=0 and bx2['y']+bx2['h']<=800 and bx2['w']>bx['w'],bx2)
    pg.screenshot(path="/tmp/shots/timer_open.png")
    # accuracy across UI changes: expand/collapse should not change remaining time
    a=pg.inner_text("#sd-time"); pg.click(".sd-chev"); pg.wait_for_timeout(600); pg.click(".sd-top .sd-clock"); pg.wait_for_timeout(500); c=pg.inner_text("#sd-time")
    secs=lambda t:int(t[:2])*60+int(t[3:])
    check("expand/collapse does not disturb the timer",0<=secs(a)-secs(c)<=3,(a,c))
    # background throttling: simulate hidden tab for 5s by moving system time forward via Date.now shift
    pg.evaluate("()=>{const off=5000,o=Date.now;Date.now=()=>o()+off}"); pg.wait_for_timeout(1300); d=pg.inner_text("#sd-time")
    check("timer is wall-clock based (still right after time passes while UI sleeps)",secs(c)-secs(d)>=5,(c,d))
    # drag to the right
    pg.click(".sd-chev") if pg.evaluate("document.getElementById('session-dock').dataset.open")=="1" else None; pg.wait_for_timeout(500)
    r=box(); pg.mouse.move(r['x']+80,r['y']+30); pg.mouse.down(); pg.mouse.move(r['x']+300,r['y']-60,steps=8); pg.mouse.up(); pg.wait_for_timeout(700)
    check("drag snaps the pill to the right edge and remembers it",pg.evaluate("document.getElementById('session-dock').dataset.x")=="r" and pg.evaluate("JSON.parse(localStorage.getItem('dabsy_session_dock_pos_v1')).x")=="r",pg.evaluate("document.getElementById('session-dock').dataset.x"))
    pg.screenshot(path="/tmp/shots/timer_moved.png")
    pg.evaluate("window.DABSy.app.openCommand()"); pg.wait_for_timeout(900)
    r=box(); check("moves out of the way (to the top) while typing",r['y']<120,r)
    pg.evaluate("window.DABSy.app.closeCommand()"); pg.wait_for_timeout(700)
    pg.evaluate("window.DABSy.session.finish(true)"); pg.wait_for_timeout(800)
    check("finishing removes the pill",pg.locator("#session-dock").count()==0 or not pg.locator("#session-dock").is_visible())
    check("no page errors",not errs,errs[:3])
    b.close()
finally: srv.terminate()
import sys; sys.exit(0 if summary() else 1)
